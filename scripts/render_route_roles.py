#!/usr/bin/env python3
"""Write docs/route-roles.md: which role each route, API endpoint and MCP tool
needs, read from the code.

The roles are declared in many places: each module's ROUTES, the route policy,
server.py's guard, the API's endpoint scopes and the MCP tools. This puts them
in one table, so a change to who may use something is a changed row in review.
tests/test_route_roles.py fails when the table is out of date, and names any
role that went down.

    python scripts/render_route_roles.py           # write the table
    python scripts/render_route_roles.py --check   # exit 1 when it is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

import homestead_agent_tools as TOOLS  # noqa: E402
import homestead_api_keys as KEYS  # noqa: E402
import homestead_api_v1 as API  # noqa: E402
import homestead_mcp as MCP  # noqa: E402
import homestead_route_policy as POLICY  # noqa: E402
import homestead_routes as ROUTES  # noqa: E402
import homestead_web_paths as WEB  # noqa: E402

OUT = ROOT / "docs" / "route-roles.md"
# Lowest first. public: no sign-in; key: any valid API key.
RANKS = ("public", "key", *ROUTES.ROLES)
# Where server.py's _api_key_guard takes an API key instead of a session.
KEY_PATHS = ("/api/v1/", MCP.PATH, "/metrics")

HEADER = """# Which role each route needs

Generated by `scripts/render_route_roles.py` from the code: edit the routes, not
this file. `tests/test_route_roles.py` fails when it is out of date, and names
any role that is lower in the code than here, so a change to who may use a
route is a changed row in review.

Roles, lowest first: `public` (no sign-in), `key` (any API key), `viewer`,
`operator`, `admin`.
"""


def unsigned(path):
    """Whether server.py's guard lets a request for path through without a session."""
    return (WEB.is_spa_route(path) or WEB.is_page_path(path) or WEB.is_public_path(path) or WEB.is_vendor_path(path)
            or (path.startswith("/js/") and path.endswith(".js")))


def takes_key(path):
    return path.startswith(KEY_PATHS[0]) or path in KEY_PATHS[1:]


def _scope_role(scope):
    return KEYS.SCOPES[scope][0] if scope else "key"


def _routes():
    """(method, path) -> (needs, declared in, takes a key)."""
    table, out = ROUTES.table(), {}
    for method, path in sorted({*table, *POLICY.POLICY}, key=lambda k: (k[1], k[0])):
        route = table.get((method, path))
        needs = "public" if unsigned(path) else POLICY.role(path, method)
        out[(method, path)] = (needs, route.module if route else "homestead_route_policy", takes_key(path))
    out[("POST", MCP.PATH)] = ("key", "server.py (homestead_mcp)", True)
    for prefix in POLICY.CODE_PREFIXES:
        out[("GET", prefix + "*")] = ("public" if unsigned(prefix) else "admin", "server.py", False)
    for path in sorted(WEB.PUBLIC):
        if not any(p == path for _, p in out):
            out[("ANY", path)] = ("public", "server.py", takes_key(path))
    return dict(sorted(out.items(), key=lambda item: (item[0][1], item[0][0])))


def _tools():
    """name -> (needs, scope, kind, approved by)."""
    out = {}
    for tool in TOOLS.TOOLS:
        approves = tool.role if tool.kind == TOOLS.DESTRUCTIVE else ""
        out[tool.name] = (_scope_role(tool.scope), tool.scope or "any key", tool.kind, approves)
    out[MCP.FOLLOW["name"]] = ("key", "any key", TOOLS.READ, "")
    return out


def current():
    """Every row's key -> (needs, approved by): what the ratchet compares."""
    rows = {("route", m, p): (needs, "") for (m, p), (needs, _, _) in _routes().items()}
    rows.update({("api", e.method, e.path): (_scope_role(e.scope), "") for e in API.ENDPOINTS})
    rows.update({("tool", "-", name): (needs, approves) for name, (needs, _, _, approves) in _tools().items()})
    return rows


def render():
    lines = [HEADER, "## HTTP routes", "",
             "Pages, app files and `/js/*.js` are public too; they are not listed.", "",
             "| Method | Path | Needs | API key | Declared in |", "|---|---|---|---|---|"]
    for (method, path), (needs, where, key) in _routes().items():
        lines.append(f"| {method} | `{path}` | {needs} | {'yes' if key else ''} | {where} |")
    lines += ["", "## API v1 endpoints", "", "Needs is the role the endpoint's scope stands for.", "",
              "| Method | Path | Needs | Scope |", "|---|---|---|---|"]
    for e in API.ENDPOINTS:
        lines.append(f"| {e.method} | `{e.path}` | {_scope_role(e.scope)} | {e.scope or 'any key'} |")
    lines += ["", "## MCP tools", "",
              "Needs is the role the tool's scope stands for. A destructive tool waits for a person with the "
              "role in Approved by.", "",
              "| Tool | Needs | Scope | Kind | Approved by |", "|---|---|---|---|---|"]
    for name, (needs, scope, kind, approves) in sorted(_tools().items()):
        lines.append(f"| `{name}` | {needs} | {scope} | {kind} | {approves} |")
    return "\n".join(lines) + "\n"


_ROW = re.compile(r"\| (?P<a>[^|]*?) \| (?P<b>[^|]*?) \| (?P<c>[^|]*?) \| (?P<d>[^|]*?) \|(?: (?P<e>[^|]*?) \|)?")


def parse(text):
    """A rendered table's rows, keyed as current() keys them."""
    rows, section = {}, None
    for line in text.splitlines():
        if line.startswith("## "):
            section = {"## HTTP routes": "route", "## API v1 endpoints": "api", "## MCP tools": "tool"}.get(line)
            continue
        found = _ROW.fullmatch(line)
        if not found or section is None or found["a"] in ("Method", "Tool") or found["a"].startswith("---"):
            continue
        if section == "tool":
            rows[("tool", "-", found["a"].strip("`"))] = (found["b"], found["e"] or "")
        else:
            rows[(section, found["a"], found["b"].strip("`"))] = (found["c"], "")
    return rows


def lowered(table, now):
    """Rows whose role in the code (now) is lower than in the table."""
    def rank(role):
        return RANKS.index(role) if role in RANKS else -1
    out = []
    for key, (needs, approves) in sorted(table.items()):
        if key not in now:
            continue
        name = f"tool {key[2]}" if key[0] == "tool" else f"{key[1]} {key[2]}"
        if rank(now[key][0]) < rank(needs):
            out.append(f"{name}: {needs} -> {now[key][0]}")
        if approves and rank(now[key][1]) < rank(approves):
            out.append(f"{name}: approved by {approves} -> approved by {now[key][1] or 'nobody'}")
    return out


def main(argv, out=OUT):
    text = render()
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{out.name} is out of date: run python scripts/render_route_roles.py")
            return 1
        print(f"{out.name} is current")
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
